// Puntos de una parábola y = a(x - h)² + k, para dibujarla
function puntosParabola(a, h, k, desde, hasta) {
  var pts = [];
  for (var x = desde; x <= hasta + 1e-9; x += 0.25) pts.push([x, a * (x - h) * (x - h) + k]);
  return pts;
}

